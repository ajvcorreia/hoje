/** The groups with only the glyphs whose keywords contain every word of `query`. */
export function searchIcons(query: string): IconGroup[] {
  const words = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (!words.length) return [...ICON_GROUPS];
  return ICON_GROUPS.map((group) => ({
    label: group.label,
    icons: group.icons.filter(([, keywords]) => words.every((word) => keywords.includes(word))),
  })).filter((group) => group.icons.length > 0);
}

const EMOJI = /\p{Extended_Pictographic}|\p{Regional_Indicator}|⃣/u;

/** The first character of `text` when it is an emoji (flags and keycaps too), else null. */
export function firstEmoji(text: string): string | null {
  const trimmed = text.trim();
  if (!trimmed) return null;
  const [first] = new Intl.Segmenter(undefined, { granularity: 'grapheme' }).segment(trimmed);
  return first && EMOJI.test(first.segment) ? first.segment : null;
}
